-- 023: 站点「上次下发时间」
--
-- 列表要展示「这个站点的配置上次什么时候真正推到 Web 服务器」。此前只有
-- conf_path（是否下发过）没有时间戳，「这个站多久没管了」得靠人翻日志。
--
-- 语义：**最后一次 deploy + reload 成功**的 unix 秒；NULL = 从未成功下发。
-- 五条写入口都会落（apply / conf PUT / regen / rollback / 停用后重新启用）——
-- 统一走公共收尾函数 finish_deploy，漏一路就会出现「配置已下发、列表显示
-- 从未下发」的假状态（本项目在多路径约束上踩过的坑，见 sites.rs 注释）。
-- 停用（移除配置）**不**更新：那是「撤下」不是「下发」，历史时间戳保持原值。
-- 铁律依旧：先同步外部状态成功，才写这个库字段。
ALTER TABLE sites ADD COLUMN last_applied_at INTEGER;
