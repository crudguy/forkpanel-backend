-- 站点「手动维护」标记：所有者直接编辑过原始 Web 服务器配置后置 1。
--
-- 动机：站点配置此前是面板自动生成的产物（表单 → render → validate → 下发），
-- 用户想加一条面板表单覆盖不到的规则只能手改文件——而手改内容会在下一次
-- 「保存并应用」时被整体覆盖。manual_conf 让「手改」成为一等状态：
--
-- 语义（manual_conf=1 且站点启用时）：
--   - 表单「保存并应用」不再重新渲染下发该站点配置——磁盘上的内容是唯一事实源
--     （库内规格字段照常更新，表单内容不丢）；
--   - UI 显示「手动维护」徽标，并提供「恢复面板托管」（按表单重新渲染覆盖）；
--   - 停用站点会移除配置文件（手动内容随之消失），停用/重新启用路径上标记清零；
--   - 删除站点照旧移除配置文件（删除动作本身就是要它下线）。
--
-- 仅「启用且 manual_conf=1」时该标记有实际意义；读侧按位解析（0/1）。
ALTER TABLE sites ADD COLUMN manual_conf INTEGER NOT NULL DEFAULT 0;
