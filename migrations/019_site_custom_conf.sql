-- 019: 站点自定义配置片段（托管的「逃生通道」）
--
-- 背景：整文件手动维护（016）解决「完全接管」，但代价是**退出表单托管**——
-- 为加一条 add_header 或一个 location，整个站点都不再随表单重新渲染。
-- 本迁移给一个中间形态：owner 写一段 nginx 片段，渲染时插在主 server 块
-- **尾部**（可放 location / add_header / 各类 server 级指令），且仍随
-- 「保存并应用」自动重新渲染——不必为了一个小改动放弃托管。
--
-- 与「手动维护」的分工：
--   custom_conf = 表单托管的一部分（进部署指纹：改了会照常触发「未同步」检测）
--   手动维护     = 整文件接管（表单跳过覆盖，直到「重新生成」或「回滚」定态）
--
-- 安全：内容为原始 nginx 文本（写坏等价于 root 级事故）→ 仅 owner 可修改
-- （应用层强制，panel-api sites.rs apply）；语法由每次下发前的 nginx -t 兜底
-- ——校验不过不下发，旧文件不动。上限 64 KiB（应用层强制）。
-- NULL = 未设置自定义片段。
ALTER TABLE sites ADD COLUMN custom_conf TEXT;
