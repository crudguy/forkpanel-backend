-- 017: 部署指纹（「未同步」判据）
--
-- 背景：手动维护（016）让「表单」与「磁盘配置」可以合法地分叉，但分叉必须是
-- **可见** 的——否则用户在面板改了 WAF 档位、点了「保存并应用」，界面显示
-- 「已保存」，而线上配置纹丝不动，两边静默不一致（真实发生过：面板 strict、
-- 文件 basic，运维只能靠肉眼比对才能发现）。
--
-- 语义：sites.conf_snapshot 保存「配置文件最后一次落盘时，表单部署相关字段的
-- 指纹」（唯一实现见 panel-api sites.rs 的 deploy_fingerprint，四处共用）：
--   - 正常 apply 下发 / conf/restore 重新生成 → 指纹 = 当前表单值
--   - conf PUT 保存手改内容             → 指纹 = 当前表单值（此刻"文件已对齐表单"）
--   - 手动维护站点 apply 跳过下发        → 指纹保持不动（文件没动）
--   - 停用（文件被移除）                → 置 NULL（无文件可比）
-- 读取侧：manual_conf=1 且（指纹为 NULL 或 ≠ 当前表单指纹）→ conf_stale=true，
-- 前端据此显示「未同步」徽标 / 配置区警示，并提供一键「重新生成配置」
-- （覆盖前自动备份到 <data_dir>/conf-backups/）。
--
-- NULL = 无记录：旧版本（016 之前转入手动维护）的行、或从未在开启此特性后
-- 落盘的行。对手动维护站点按「未同步」对待（有疑问时向"提示"倾斜，而不是
-- 假装同步）。
ALTER TABLE sites ADD COLUMN conf_snapshot TEXT;
