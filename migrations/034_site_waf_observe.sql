-- 034：站点 WAF 观察模式（P1-6a）。
--
-- 背景：WAF 一开就拦截，误杀压力全压在用户身上——他们既看不到"会误杀多少"，
-- 也没有低成本的反悔方式。观察模式让 WAF 只记录不拦截，先把真实流量里会命中
-- 的请求量出来，再决定是否转为拦截。
--
-- 0 = 正常拦截（默认，保持既有行为不变）；1 = 观察模式。
-- ⚠ 只作用于 WAF 关键词规则。敏感文件拒绝、IP ACL、限速/连接数**不受影响**：
-- 那几条是确定的越权或资源边界，没有"先观察"的余地（放行 .env 等于敞开源码）。
ALTER TABLE sites ADD COLUMN waf_observe INTEGER NOT NULL DEFAULT 0;
